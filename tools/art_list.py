#!/usr/bin/env python3
"""Write production/art/ILLUSTRATION_LIST.md: every planned illustration with its prompt.
Shared template lines (format, style, final requirements, references) are printed once per
kind; each entry lists every remaining line of its exact prompt, so shared lines + entry lines
= the prompt sent to the image model (production/art/gpt/prompts/<ID>.txt holds the full text
for queued entries). Owner-authored prompts are printed in full."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import art_generate as g  # noqa: E402

ORDER = [("cover", "Cover"), ("chapter", "Chapter openers"), ("world", "World sections"), ("climate", "Climates"),
         ("bastion", "Bastions"), ("ancestry", "Ancestries"), ("background", "Backgrounds"), ("class", "Classes"),
         ("item", "Equipment"), ("tradition", "Spell and power tiers"), ("monster", "Monsters"), ("boss", "Bosses"),
         ("scenario", "Scenarios"), ("campaign", "Stronghold rooms")]


def main():
    cfg, entries = g.CFG, g.entries()
    v2 = cfg["prompt_v2"]
    sels = g.load(g.SELECTIONS, {})
    owner = g.load(g.OWNER_PROMPTS, {})
    shared = {v2["style_scene"], v2["style_figure"], v2["final_scene"], v2["final_figure"], v2["reference"], "STYLE REFERENCES"}
    for kind in ("scene", "figure", "still"):
        for aw in g.ASPECT_WORDS.values():
            shared |= {x.format(aspect_words=aw) for x in v2["format_" + kind]}
    for f in cfg["families"].values():
        shared.add(f["framing"])
    out = ["# Planned illustrations", "",
           f"{len(entries)} unique illustrations, generated by `tools/art_list.py` from the catalog, subject plan, briefs and "
           "`config/art_style.json`. Uniqueness is enforced by `tools/art_catalog.py`. Status marks: ✓ approved, ◐ received or "
           "proposed and awaiting review, ★ owner-authored prompt.", "",
           "## Shared template", "", "Every prompt has these sections, in order:",
           "1. title;", "2. introduction;", "3. format;", "4. composition;", "5. subject details;", "6. activity;",
           "7. source text (verbatim flavour);", "8. style and atmosphere;", "9. final requirements;", "10. style references.", "",
           "The lines below are shared. Each entry lists only its own lines.", "",
           "**Introduction:** " + v2["intro"], "",
           "**Format, scenes:** " + " ".join(v2["format_scene"]), "",
           "**Format, figures:** " + " ".join(v2["format_figure"]), "",
           "**Format, still lifes:** " + " ".join(v2["format_still"]), "",
           "**Style, scenes:** " + v2["style_scene"], "",
           "**Style, figures and still lifes:** " + v2["style_figure"], "",
           "**Final, scenes:** " + v2["final_scene"], "",
           "**Final, figures and still lifes:** " + v2["final_figure"], "",
           "**References:** " + v2["reference"], ""]
    for fam, label in ORDER:
        es = [e for e in entries if e["family"] == fam]
        f = cfg["families"][fam]
        out += [f"## {label} ({len(es)})", "", f"Printed {f['print_w_in']} in wide · aspect {f['aspect']}. Family framing: {f['framing']}", ""]
        for n, e in enumerate(es, 1):
            s = sels.get(e["id"], {}).get("status", "")
            mark = " ✓" if s in ("approved", "anchor-approved", "auto-selected") else " ◐" if s else ""
            mark += " ★" if e["id"] in owner else ""
            prompt = g.prompt_for(e, False)
            if e["id"] in owner:
                body = prompt
            else:
                body = "\n".join(l for l in prompt.split("\n") if l.strip() and l not in shared
                                 and not l.startswith(("FORMAT AND", "ARTISTIC STYLE")) and l != "FINAL VISUAL REQUIREMENTS")
            out += [f"### {n}. {e['title'] if fam not in ('cover', 'chapter') else g.label(e).title()}{mark}", "",
                    f"`{e['id']}`", "", "```text", body, "```", ""]
    (ROOT / "production/art/ILLUSTRATION_LIST.md").write_text("\n".join(out) + "\n")
    print(len(entries))


if __name__ == "__main__":
    main()
