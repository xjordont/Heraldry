#!/usr/bin/env python3
"""Write production/art/ILLUSTRATION_LIST.md: every planned illustration with its exact prompt.
Shared prompt blocks (style, references, family format, exclusions) are printed once; each
entry lists only its own part, so shared blocks + entry part = the prompt sent to the model."""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import art_generate as g  # noqa: E402

ORDER = [("cover", "Cover"), ("chapter", "Chapter openers"), ("world", "World sections"), ("climate", "Climates"),
         ("bastion", "Bastions"), ("ancestry", "Ancestries"), ("background", "Backgrounds"), ("class", "Classes"),
         ("item", "Equipment"), ("tradition", "Spell and power tiers"), ("monster", "Monsters"), ("boss", "Bosses"),
         ("scenario", "Scenarios"), ("campaign", "Stronghold rooms")]


def main():
    cfg, entries = g.CFG, g.entries()
    sels = g.load(g.SELECTIONS, {})
    chs = [c["title"] or "" for c in json.loads((ROOT / "build/blocks.json").read_text())["chapters"]]
    chname = {f"ART-CH{int(t.split('.')[0]):02d}-002": "Chapter " + t for t in chs if t.split(".")[0].isdigit()}
    out = ["# Planned illustrations", "",
           f"{len(entries)} unique illustrations. Generated by `tools/art_list.py` from `production/art/SPOT_CATALOG.json`, "
           "`production/art/SUBJECT_PLAN.json` and `config/art_style.json`; regenerate after any change. "
           "✓ = generated test anchor awaiting approval. Uniqueness is enforced by `tools/art_catalog.py` (the build fails on a duplicate subject "
           "or an unseparated name collision).", "",
           "## Shared prompt blocks", "", "Every prompt is assembled in this order:", "",
           "1. **Style**:", "", "> " + cfg["style"], "",
           "2. **References** (attached images):", "", "> " + cfg["reference_instruction"], "",
           "3. **Format**: the family block shown under each heading below.", "",
           "4. **Entry**: the entry's own part, listed with each item.", "",
           "5. **Exclusions**:", "", "> " + cfg["exclusions"], ""]
    shared = {cfg["style"], cfg["reference_instruction"], cfg["exclusions"]}
    for fam, label in ORDER:
        es = [e for e in entries if e["family"] == fam]
        f = cfg["families"][fam]
        out += [f"## {label} ({len(es)})", "",
                f"Printed {f['print_w_in']} in wide · aspect {f['aspect']} · {f['size']} · format block:", "",
                "> FORMAT: " + f["framing"] + f" Aspect ratio {f['aspect']}.", ""]
        for n, e in enumerate(es, 1):
            parts = [p for p in g.prompt_for(e, True).split("\n\n") if p not in shared and not p.startswith("FORMAT:")]
            name = {"cover": "Front cover", "chapter": chname.get(e["id"], e["id"])}.get(fam, e["title"])
            mark = " ✓" if e["id"] in sels else ""
            out += [f"**{n}. {name}**{mark} `{e['id']}`", ""] + ["\n>\n".join("> " + p.replace("\n", " ") for p in parts), ""]
    (ROOT / "production/art/ILLUSTRATION_LIST.md").write_text("\n".join(out) + "\n")
    print(len(entries))


if __name__ == "__main__":
    main()
